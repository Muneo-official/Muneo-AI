def detect_region(data: dict) -> str:
    """location 필드를 우선 탐색하고, 없으면 나머지 텍스트에서 지역명을 찾는다.

    업체명 패턴("서울24호" 등)이 지역으로 오인식되는 걸 막기 위해 나머지 텍스트에서는
    해당 패턴을 제거한 뒤 탐색한다. 감지 실패 시 "기타" 반환.
    """
    location = data.get("location", "")
    if location:
        for region, keywords in REGION_PATTERNS:
            for kw in keywords:
                if kw in location:
                    return region

    other_texts = [
        data.get("post_title", ""),
        (data.get("body_text") or "")[:500],
        (data.get("request_body_text") or "")[:500],
    ]
    combined = _COMPANY_NAME_RE.sub("", " ".join(t for t in other_texts if t))

    for region, keywords in REGION_PATTERNS:
        for kw in keywords:
            if kw in combined:
                return region

    return "기타"
